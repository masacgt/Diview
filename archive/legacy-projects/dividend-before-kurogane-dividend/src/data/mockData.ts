export function getStockFinancialProfile(code: string, currentPrice?: number, dps?: number): StockFinancialProfile {
  const base = stockProfileCatalog[code] || {
    payoutRatio: 35.0,
    payoutStatusBadge: '適正レンジ内 (黄金比率)',
    equityRatio: 40.0,
    equityRatioSub: '業界高水準・安定',
    doePolicy: '3.0% (DOE)',
    doePolicySub: '安定還元基準',
    netDeRatio: '0.10倍 (健全財務)',
    operatingMargin: 10.0,
    fcfStatus: '黒字維持（配当余力 十分）',
    modelType: '高配当ディフェンシブ型',
    healthScore: 88,
    healthGrade: 'A判定',
    healthEvaluation: '適正健全水準',
    consecutiveYears: 5,
    noCutYears: 10,
    growthRate: 5.0,
    eps: currentPrice ? Math.round(currentPrice / 15) : 100,
    bps: currentPrice ? Math.round(currentPrice * 0.9) : 1000,
    recordMonths: '3月末 / 9月末',
    payoutSchedule: '6月下旬 / 12月中旬',
    healthDiagnosisComment: '自己資本比率は健全目安を維持しており、財務基盤は安定。本業のキャッシュ創出力と配当余力を備えており、継続的な還元が期待されます。'
  };

  const effPrice = typeof currentPrice === 'number' && currentPrice > 0 ? currentPrice : 1000;
  const effDps = typeof dps === 'number' && dps >= 0 ? dps : (base.eps * (base.payoutRatio / 100));

  const perVal = base.eps > 0 ? (effPrice / base.eps) : 0;
  const pbrVal = base.bps > 0 ? (effPrice / base.bps) : 0;
  const per = perVal > 0 ? `${perVal.toFixed(1)}倍` : '-';
  const pbr = pbrVal > 0 ? `${pbrVal.toFixed(2)}倍` : '-';

  // Dynamic Valuation zone evaluation
  let valuationStatus = base.buySignalZone || '適正・中立ゾーン';
  let valuationTimingComment = '現在の株価は過去のヒストリカル指標に照らし合わせてニュートラルな巡航レンジです。ドルコスト平均法による積立や配当再投資に適しています。';

  const yieldRate = effPrice > 0 ? (effDps / effPrice) * 100 : 0;
  if (yieldRate >= 4.0 || (perVal > 0 && perVal < 10 && pbrVal < 0.9)) {
    valuationStatus = '超割安ゾーン（絶好の買場）';
    valuationTimingComment = `配当利回りが${yieldRate.toFixed(2)}%に達し、PER(${per})・PBR(${pbr})ともに歴史的割安圏にあります。インカム狙いの積極的な押し目買いに相応しい水準です。`;
  } else if (yieldRate >= 2.5 || (perVal > 0 && perVal < 14)) {
    valuationStatus = '超割安ゾーン（検討圏）';
    valuationTimingComment = `配当利回り${yieldRate.toFixed(2)}%と下値抵抗力が高く、PER(${per})も妥当圏です。毎月の定額買付や新規エントリーを前向きに検討できる価格帯です。`;
  } else if (perVal > 25) {
    valuationStatus = '高PER・プレミアム評価圏';
    valuationTimingComment = `株価の上昇によりPER(${per})が高水準となっています。成長期待が織り込まれているため、押し目を待っての慎重な買付が推奨されます。`;
  }

  // Dynamic PER / PBR evaluation
  let perEvaluation = base.perEvaluation || '適正水準';
  if (perVal > 0) {
    if (perVal < 14) perEvaluation = '市場平均比で割安';
    else if (perVal <= 20) perEvaluation = '適正水準';
    else perEvaluation = '高PER・成長評価';
  }

  let pbrEvaluation = base.pbrEvaluation || '資本効率適正圏';
  if (pbrVal > 0) {
    if (pbrVal <= 1.0) pbrEvaluation = '解散価値割れ（割安）';
    else if (pbrVal <= 1.3) pbrEvaluation = '資本効率適正圏';
    else pbrEvaluation = 'プレミアム評価圏';
  }

  const yieldRangeMin = base.yieldRangeMin || +(Math.max(1.0, yieldRate * 0.75)).toFixed(2);
  const yieldRangeAvg = base.yieldRangeAvg || +(yieldRate * 0.88).toFixed(2);
  const yieldRangeMax = base.yieldRangeMax || +(yieldRate * 1.15).toFixed(2);
  const yieldRangeBadge = base.yieldRangeBadge || (yieldRate >= yieldRangeAvg ? '過去5年平均超え' : '過去平均水準圏');

  const valuationScore = base.valuationScore || Math.min(98, Math.max(50, Math.round(72 + (yieldRate - yieldRangeAvg) * 20)));

  const buySignalZone = base.buySignalZone || (yieldRate >= yieldRangeAvg ? '超割安ゾーン（検討圏）' : '適正中立ゾーン');
  const buySignalTitle = base.buySignalTitle || `【${base.modelType}】PER ${per} × PBR ${pbr}`;
  const buySignalBadge = base.buySignalBadge || (yieldRate >= yieldRangeAvg ? '絶好の買増し検討期' : '定期買付推奨圏');
  const buySignalComment = base.buySignalComment || `PER ${per}・PBR ${pbr}と、日経平均平均（PER 15倍・PBR 1.4倍）を大幅に下回る優良バリュー水準。高収益性とキャッシュ創出力に対して割安に放置されており、配当再投資や中期的な買い増しに最適な好機シグナルです。`;

  return {
    ...base,
    per,
    pbr,
    valuationStatus,
    valuationTimingComment,
    valuationScore,
    yieldRangeMin,
    yieldRangeAvg,
    yieldRangeMax,
    yieldRangeBadge,
    perEvaluation,
    pbrEvaluation,
    buySignalZone,
    buySignalTitle,
    buySignalBadge,
    buySignalComment
  };
}

